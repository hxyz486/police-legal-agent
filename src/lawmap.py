def expand(question, max_variants=MAX_VARIANTS):
    """返回若干"法条措辞扩展变体"（确定性、零模型调用）。

    命中多条映射时按**触发词长度降序**优先——触发词越长越具体
    （如"个人信息"优先于"告知"），避免被泛化词抢走变体名额。
    """
    q = question or ""
    if not q:
        return []
    hits = []
    for keys, terms in TABLE:
        best = max((len(k) for k in keys if k in q), default=0)
        if best:
            hits.append((best, terms))
    if not hits:
        return []
    hits.sort(key=lambda x: -x[0])
    out = []
    for _, t in hits:
        if t not in out:
            out.append(t)
        if len(out) >= max_variants:
            break
    log.info("法条映射字典命中 %d 条，取 %d 条变体：%s", len(hits), len(out),
             [t[:28] for t in out])
    return out
